"""Turn original school photos into the small WebP files the site serves.

Usage:
    python scripts/optimize_photos.py <originals_dir>

Reads scripts/photos-manifest.json. Each photo there is looked up as
<originals_dir>/<id>.jpg (or the "src" filename it names), then:
  - rotated upright from its EXIF orientation,
  - cropped if the entry has a "crop" box (fractions of width/height),
  - resized to every width in "widths" that the original can supply,
  - encoded at quality 74, or the entry's "quality" if it has one,
  - saved as assets/media/photos/<id>-<width>.webp with no EXIF, so no
    GPS location or camera details are published.
It then rewrites _data/photos.yml, which the templates read.

Needs Pillow (pip install pillow). Originals stay out of the repo.
"""
import json
import os
import sys

from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "assets", "media", "photos")
DATA = os.path.join(ROOT, "_data", "photos.yml")
QUALITY = 74


def q(s):
    # JSON strings are valid YAML double-quoted scalars; keep Hindi readable.
    return json.dumps(s, ensure_ascii=False)


def main(src_dir):
    with open(os.path.join(ROOT, "scripts", "photos-manifest.json"), encoding="utf-8") as f:
        manifest = json.load(f)
    os.makedirs(OUT_DIR, exist_ok=True)

    lines = [
        "# Generated by scripts/optimize_photos.py from scripts/photos-manifest.json.",
        "# Edit the manifest and re-run the script rather than editing this file.",
        "#",
        "# items: one entry per photo. Files live at",
        "#   assets/media/photos/<id>-<width>.webp for each width listed.",
        "#   w/h are the pixel size of the largest file; templates use them for",
        "#   the aspect ratio so the page does not jump while photos load.",
        "# slots: which photo fills each placeholder in the design.",
        "",
        "items:",
    ]
    total = 0
    for pid, p in manifest["items"].items():
        im = Image.open(os.path.join(src_dir, p.get("src", pid + ".jpg")))
        im = ImageOps.exif_transpose(im).convert("RGB")
        if "crop" in p:
            x0, y0, x1, y1 = p["crop"]
            W, H = im.size
            im = im.crop((round(x0 * W), round(y0 * H), round(x1 * W), round(y1 * H)))
        widths = [w for w in p["widths"] if w <= im.width] or [im.width]
        for w in widths:
            h = round(im.height * w / im.width)
            out = os.path.join(OUT_DIR, f"{pid}-{w}.webp")
            im.resize((w, h), Image.LANCZOS).save(out, "WEBP", quality=p.get("quality", QUALITY), method=6)
            total += os.path.getsize(out)
        top = widths[-1]
        lines += [
            f"  {pid}:",
            f"    widths: [{', '.join(str(w) for w in widths)}]",
            f"    w: {top}",
            f"    h: {round(im.height * top / im.width)}",
        ]
        if p.get("pos"):
            lines.append(f"    pos: {q(p['pos'])}")
        if p.get("gallery"):
            lines.append(f"    gallery: {p['gallery']}")
        lines += [
            "    alt:",
            f"      en: {q(p['alt']['en'])}",
            f"      hi: {q(p['alt']['hi'])}",
        ]
        print(f"{pid}: {widths} from {im.size}")

    lines += ["", "slots:"]
    for name, val in manifest["slots"].items():
        if isinstance(val, list):
            lines.append(f"  {name}: [{', '.join(v if v else 'null' for v in val)}]")
        else:
            lines.append(f"  {name}: {val}")
    lines += ["", "gallery_order: [" + ", ".join(manifest["gallery_order"]) + "]", ""]

    with open(DATA, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {DATA}; {total / 1024:.0f} KB of WebP")


if __name__ == "__main__":
    main(sys.argv[1])
