"""Turn original school photos into the small WebP files the site serves.

Usage:
    python scripts/optimize_photos.py <originals_dir>

Reads scripts/photos-manifest.json. Each photo there is looked up as
<originals_dir>/<id>.jpg (or the "src" filename it names), then:
  - rotated upright from its EXIF orientation,
  - cropped if the entry has a "crop" box (fractions of width/height),
  - given a gentle, global clean-up: levels stretched without shifting
    colour, a touch more vibrance, and sharpening after each resize. Nothing
    in the frame is retouched. "enhance": false skips the clean-up and
    "sharpen": false the sharpening for one photo,
  - if the entry has a "grade" block, finished with scripts/grade.py first
    (white balance, exposure, shadow lift, clarity, straightened verticals;
    see that file for every setting). Needs numpy and opencv-python-headless,
  - skipped (its WebP files are kept as they are) when the original is not
    in <originals_dir>, so one photo can be redone without the whole set,
  - resized to every width in "widths" that the original can supply,
  - encoded at quality 74, or the entry's "quality" if it has one,
  - saved as assets/media/photos/<id>-<width>.webp with no EXIF, so no
    GPS location or camera details are published.
It then rewrites _data/photos.yml, which the templates read.

Needs Pillow (pip install pillow). Originals stay out of the repo.
"""
import json
import os
import sys

from PIL import Image, ImageEnhance, ImageFilter, ImageOps

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "assets", "media", "photos")
DATA = os.path.join(ROOT, "_data", "photos.yml")
QUALITY = 74


def clean_up(im):
    # Phone shots of the campus are often hazy under a bright sky. Clip the
    # darkest and brightest 0.3% and stretch the rest, the same amount on
    # every channel so whites stay white; then a little more colour.
    im = ImageOps.autocontrast(im, cutoff=(0.3, 0.3), preserve_tone=True)
    return ImageEnhance.Color(im).enhance(1.06)


# Downscaling softens edges; this restores them without crunching the
# WhatsApp-compressed originals (threshold skips flat areas and noise).
SHARPEN = ImageFilter.UnsharpMask(radius=0.8, percent=55, threshold=3)


def q(s):
    # JSON strings are valid YAML double-quoted scalars; keep Hindi readable.
    return json.dumps(s, ensure_ascii=False)


def _entry(pid, p, widths, top, top_h):
    out = [
        f"  {pid}:",
        f"    widths: [{', '.join(str(w) for w in widths)}]",
        f"    w: {top}",
        f"    h: {top_h}",
    ]
    if p.get("pos"):
        out.append(f"    pos: {q(p['pos'])}")
    if p.get("gallery"):
        out.append(f"    gallery: {p['gallery']}")
    out += [
        "    alt:",
        f"      en: {q(p['alt']['en'])}",
        f"      hi: {q(p['alt']['hi'])}",
    ]
    return out


def main(src_dir):
    with open(os.path.join(ROOT, "scripts", "photos-manifest.json"), encoding="utf-8") as f:
        manifest = json.load(f)
    os.makedirs(OUT_DIR, exist_ok=True)

    lines = [
        "# Generated by scripts/optimize_photos.py from scripts/photos-manifest.json.",
        "# Edit the manifest and re-run the script rather than editing this file.",
        "#",
        "# items: one entry per photo. Files live at",
        "#   assets/media/photos/<id>-<width>.webp for each width listed.",
        "#   w/h are the pixel size of the largest file; templates use them for",
        "#   the aspect ratio so the page does not jump while photos load.",
        "# slots: which photo fills each placeholder in the design.",
        "",
        "items:",
    ]
    total = 0
    for pid, p in manifest["items"].items():
        src = os.path.join(src_dir, p.get("src", pid + ".jpg"))
        if not os.path.exists(src):
            # Keep the published files; read the size from the largest one.
            have = [w for w in p["widths"] if os.path.exists(os.path.join(OUT_DIR, f"{pid}-{w}.webp"))]
            if not have:
                sys.exit(f"{pid}: no original at {src} and no published WebP")
            with Image.open(os.path.join(OUT_DIR, f"{pid}-{have[-1]}.webp")) as old:
                ow, oh = old.size
            widths, top, top_h = have, have[-1], oh
            print(f"{pid}: kept {have} (no original supplied)")
            lines += _entry(pid, p, widths, top, top_h)
            continue
        im = Image.open(src)
        im = ImageOps.exif_transpose(im).convert("RGB")
        if p.get("grade"):
            from grade import grade
            im = grade(im, p["grade"])
        if "crop" in p:
            x0, y0, x1, y1 = p["crop"]
            W, H = im.size
            im = im.crop((round(x0 * W), round(y0 * H), round(x1 * W), round(y1 * H)))
        if p.get("enhance", True):
            im = clean_up(im)
        widths = [w for w in p["widths"] if w <= im.width] or [im.width]
        for w in widths:
            h = round(im.height * w / im.width)
            out = os.path.join(OUT_DIR, f"{pid}-{w}.webp")
            small = im.resize((w, h), Image.LANCZOS)
            if p.get("sharpen", True):
                small = small.filter(SHARPEN)
            small.save(out, "WEBP", quality=p.get("quality", QUALITY), method=6)
            total += os.path.getsize(out)
        top = widths[-1]
        lines += _entry(pid, p, widths, top, round(im.height * top / im.width))
        print(f"{pid}: {widths} from {im.size}")

    lines += ["", "slots:"]
    for name, val in manifest["slots"].items():
        if isinstance(val, list):
            lines.append(f"  {name}: [{', '.join(v if v else 'null' for v in val)}]")
        else:
            lines.append(f"  {name}: {val}")
    lines += ["", "gallery_order: [" + ", ".join(manifest["gallery_order"]) + "]", ""]

    with open(DATA, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {DATA}; {total / 1024:.0f} KB of WebP")


if __name__ == "__main__":
    main(sys.argv[1])
